import assert from 'node:assert/strict'
import { readFileSync,writeFileSync } from 'node:fs'
import { parseEnv } from 'node:util'
import { pathToFileURL } from 'node:url'
const {chromium}=await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href)
const config=parseEnv(readFileSync(process.env.DEMO_ENV_FILE,'utf8'))
assert.equal(config.VITE_SUPABASE_URL,'https://itjlykpjmlcvanqpmkmc.supabase.co')
const root=process.env.DEMO_APP_URL||'http://localhost:5179'
assert.ok(['http://localhost:5179','https://chinese-territory-app-demo.vercel.app'].includes(root))
const browser=await chromium.launch({headless:true})
try {
  const context=await browser.newContext({viewport:{width:430,height:932},serviceWorkers:'block'})
  await context.route('**/*.supabase.co/**',route=>{
    assert.equal(new URL(route.request().url()).origin,config.VITE_SUPABASE_URL,'Production network request blocked')
    return route.continue()
  })
  const page=await context.newPage(),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(root)
  await page.locator('#login-id').fill(config.TEST_LOGIN_ID)
  await page.locator('#pin').fill(config.TEST_LOGIN_PIN)
  await page.locator('.login-form button[type=submit]').click()
  await page.locator('.bottom-nav').waitFor({timeout:60000})
  await page.evaluate(()=>{history.pushState(null,'','/calendar');dispatchEvent(new PopStateEvent('popstate'))})
  await page.waitForTimeout(1800)
  await page.locator('.mobile-calendar-day').filter({hasText:/^25$/}).click()
  await page.locator('.gs-event-block button').first().waitFor({timeout:20000})
  await page.screenshot({path:'scratch/group-service-calendar-mobile.png',fullPage:true})
  assert.equal(await page.locator('.gs-event-block').count(),1)
  assert.equal(await page.locator('.gs-event-block button').count(),2)
  await page.getByRole('button',{name:'일정 추가',exact:true}).click()
  await page.locator('.gs-editor').waitFor()
  await page.getByRole('button',{name:'집단봉사',exact:true}).click()
  await page.getByLabel('동탄',{exact:true}).check()
  await page.getByLabel('신갈',{exact:true}).check()
  await page.getByLabel('제목',{exact:true}).fill('연합 집단봉사')
  await page.setViewportSize({width:320,height:740})
  await page.evaluate(()=>{document.querySelector('#root').style.zoom='1.25';document.querySelector('#root').style.setProperty('--app-zoom','1.25')})
  await page.screenshot({path:'scratch/group-service-editor-mobile-320.png',fullPage:true})
  const overflow=await page.locator('.gs-editor').evaluate(el=>({scroll:el.scrollWidth,width:el.clientWidth}))
  assert.ok(overflow.scroll<=overflow.width+1,JSON.stringify(overflow))
  await page.locator('.gs-editor header button').click()
  await page.setViewportSize({width:430,height:932})
  await page.evaluate(()=>{document.querySelector('#root').style.zoom='1';document.querySelector('#root').style.setProperty('--app-zoom','1')})
  await page.locator('.gs-event-block button').first().click()
  await page.getByRole('link',{name:/화상 모임 참여/}).waitFor({timeout:20000})
  await page.screenshot({path:'scratch/group-service-meeting-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'더보기',exact:true}).last().click()
  await page.getByRole('button',{name:'편집',exact:true}).click()
  await page.locator('.gs-editor').waitFor()
  await page.getByLabel(/함께 수정/).check()
  await page.getByRole('button',{name:'저장',exact:true}).click()
  await page.getByRole('button',{name:'알림 없이 저장',exact:true}).click()
  await page.locator('.gs-editor').waitFor({state:'hidden',timeout:20000})
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(`${root}/calendar`)
  await page.locator('.day-events .gs-event-block').first().waitFor({timeout:30000})
  await page.screenshot({path:'scratch/group-service-calendar-desktop.png',fullPage:true})
  assert.ok(await page.locator('.day-events .gs-event-block').count()>=2)
  const cell=page.locator('.day-events').filter({has:page.locator('.gs-event-block')}).first()
  assert.ok(await cell.evaluate(el=>el.scrollHeight<=el.clientHeight+1),'Both demo time slots must fit the desktop cell')
  assert.ok((await page.evaluate(()=>document.documentElement.scrollWidth))<=1440)
  console.log(JSON.stringify({mobileGrouped:true,desktopGrouped:true,smallEditorNoOverflow:true,virtualAccessVisible:true,pairedSave:true,errors}))
  writeFileSync('scratch/group-service-ui-errors.json',JSON.stringify(errors))
  await context.close()
  const fixture=JSON.parse(readFileSync('scratch/group-service-fixture.json','utf8'))
  const user=fixture.actors.find(a=>a.role==='user')
  assert.ok(user.name.startsWith(fixture.marker))
  const member=await browser.newContext({viewport:{width:430,height:932},serviceWorkers:'block'})
  await member.route('**/*.supabase.co/**',route=>{
    assert.equal(new URL(route.request().url()).origin,config.VITE_SUPABASE_URL)
    return route.continue()
  })
  const memberPage=await member.newPage()
  await memberPage.goto(root)
  await memberPage.locator('#login-id').fill(user.name)
  await memberPage.locator('#pin').fill('0000')
  await memberPage.locator('.login-form button[type=submit]').click()
  await memberPage.locator('.bottom-nav').waitFor({timeout:60000})
  await memberPage.goto(`${root}/calendar?openEvent=${fixture.eventIds[0]}`)
  await memberPage.getByRole('link',{name:/화상 모임 참여/}).waitFor({timeout:30000})
  await memberPage.getByRole('button',{name:'신청하기',exact:true}).click()
  await memberPage.getByRole('button',{name:'신청취소',exact:true}).waitFor({timeout:20000})
  await memberPage.screenshot({path:'scratch/group-service-member-applied.png',fullPage:true})
  await memberPage.getByRole('button',{name:'신청취소',exact:true}).click()
  await memberPage.getByRole('button',{name:'신청하기',exact:true}).waitFor({timeout:20000})
  await memberPage.evaluate(id=>localStorage.setItem(`chsLanguage:${id}`,'zh'),user.id)
  await memberPage.goto(`${root}/calendar?openEvent=${fixture.eventIds[0]}`)
  await memberPage.getByRole('link',{name:/加入线上聚会/}).waitFor({timeout:30000})
  await memberPage.screenshot({path:'scratch/group-service-member-chinese.png',fullPage:true})
  console.log(JSON.stringify({ungroupedMemberApplication:true,memberCancellation:true,chineseVirtualAccess:true}))
  await member.close()
} finally {await browser.close()}
