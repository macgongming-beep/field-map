create function public.rename_user_name_references(p_token uuid,p_old text,p_new text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_result jsonb;
begin
  v_result := private.rename_user_name_references(p_token,p_old,p_new);
  if coalesce((v_result->>'ok')::boolean,false) then
    update public.service_meeting_notes set event_leader_snapshot=public.rename_in_name_list(event_leader_snapshot,p_old,p_new),updated_at=clock_timestamp()
    where p_old=any(select btrim(v) from unnest(string_to_array(event_leader_snapshot,',')) v);
  end if;
  return v_result;
end $$;
