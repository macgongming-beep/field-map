-- Independent of special_periods: meeting collections never affect service statistics.
create table public.service_meeting_collections (
  id integer generated by default as identity primary key,
  name_ko text not null check (length(btrim(name_ko)) between 1 and 160),
  name_zh text not null default '' check (length(name_zh) <= 160),
  start_date date not null,
  end_date date not null,
  home_visible_until date not null,
  home_position text not null default 'after_service' check (home_position in ('after_service', 'top')),
  collapse_suggestions boolean not null default true,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  archived_at timestamptz,
  check (start_date <= end_date and end_date <= home_visible_until)
);

create table public.service_meeting_notes (
  id integer generated by default as identity primary key,
  event_id integer unique references public.calendar_events(id) on delete set null,
  collection_id integer not null references public.service_meeting_collections(id) on delete restrict,
  title_ko text not null check (length(btrim(title_ko)) between 1 and 200),
  title_zh text not null default '' check (length(title_zh) <= 200),
  body_ko text not null check (length(btrim(body_ko)) between 1 and 30000),
  body_zh text not null default '' check (length(body_zh) <= 30000),
  excerpt_ko text not null,
  excerpt_zh text not null,
  reading_minutes_ko integer not null,
  reading_minutes_zh integer not null,
  event_date_snapshot date not null,
  event_time_snapshot text not null default '',
  event_place_snapshot text not null default '',
  event_leader_snapshot text not null default '',
  author_user_id integer references public.app_users(id) on delete set null,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  archived_at timestamptz
);
create index service_meeting_notes_collection_date on public.service_meeting_notes(collection_id, event_date_snapshot, event_time_snapshot);

alter table public.service_meeting_collections enable row level security;
alter table public.service_meeting_notes enable row level security;
revoke all on public.service_meeting_collections, public.service_meeting_notes from public, anon, authenticated;
grant select on public.service_meeting_collections, public.service_meeting_notes to anon, authenticated;
create policy meeting_collections_read on public.service_meeting_collections for select to anon, authenticated
