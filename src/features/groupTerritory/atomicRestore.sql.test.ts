// @vitest-environment node
import { PGlite } from '@electric-sql/pglite'
import { afterAll, beforeAll, beforeEach, expect, test } from 'vitest'
import { atomicRestoreSql } from '../../../scripts/atomicRestore.mjs'
import { groupTerritoryRestoreFixture } from '../../../scripts/fixtures/groupTerritoryRestoreFixture.mjs'

let db: PGlite
const query = async (sql: string) => (await db.query(sql)).rows
const restore = (payload: Record<string, Record<string, unknown>[]>, replace = false) => db.exec(atomicRestoreSql(payload,{replace}))
async function rejected(sql: string, message: string) {
  await db.exec('savepoint rejected')
  await expect(db.exec(sql)).rejects.toThrow(message)
  await db.exec('rollback to rejected;release rejected')
}
beforeAll(async () => {
  db = new PGlite()
  await db.exec(groupTerritoryRestoreFixture())
  await db.exec(`create table review_tasks(id bigint generated always as identity primary key,title text not null);
    create table buildings(id bigint primary key);
    create table units(id bigint generated by default as identity primary key,building_id bigint references buildings);
    create table restore_side_effects(id int);
    create table private.event_assignment_revisions(event_id int primary key references calendar_events,revision bigint not null);
    insert into calendar_events(id) values(100);
    insert into private.event_assignment_revisions values(100,7);
    create function forbidden_restore_effect() returns trigger language plpgsql as $$begin
      insert into restore_side_effects values(1);return new;end $$;
    create trigger auto_session_or_notification after insert on review_tasks for each row execute function forbidden_restore_effect();
    create trigger disabled_effect after insert on review_tasks for each row execute function forbidden_restore_effect();
    alter table review_tasks disable trigger disabled_effect;
    grant all on review_tasks to authenticated;grant usage on schema private to authenticated;`)
},30000)
beforeEach(async () => { await db.exec('rollback;begin;truncate review_tasks,restore_side_effects,units,buildings restart identity') })
afterAll(async () => { await db.close() })

test('identity restore suppresses side effects, resets sequence and restores exact trigger states', async () => {
  await restore({review_tasks:[{id:42,title:'Recovered'}]})
  expect(await query('select * from review_tasks')).toEqual([{id:42,title:'Recovered'}])
  expect(await query('select * from restore_side_effects')).toEqual([])
  expect(await query("select tgname,tgenabled from pg_trigger where tgrelid='review_tasks'::regclass order by tgname")).toEqual([
    {tgname:'auto_session_or_notification',tgenabled:'O'},{tgname:'disabled_effect',tgenabled:'D'},
  ])
  expect(Number((await query("insert into review_tasks(title) values('Next') returning id"))[0].id)).toBeGreaterThan(42)
  expect(await query('select * from restore_side_effects')).toEqual([{id:1}])
})

test('late FK failure rolls back earlier tables and trigger changes; repaired retry is idempotent', async () => {
  await rejected(atomicRestoreSql({review_tasks:[{id:42,title:'Recovered'}],units:[{id:1,building_id:99}]}),'foreign key')
  expect(await query('select * from review_tasks')).toEqual([])
  expect(await query('select * from units')).toEqual([])
  expect(await query("select tgenabled from pg_trigger where tgname='auto_session_or_notification'")).toEqual([{tgenabled:'O'}])
  await restore({review_tasks:[{id:42,title:'Recovered'}],units:[{id:1,building_id:99}],buildings:[{id:99}]})
  await db.exec('commit;begin')
  await restore({review_tasks:[{id:42,title:'Changed'}],units:[{id:1,building_id:99}],buildings:[{id:99}]})
  expect(await query('select * from review_tasks')).toEqual([{id:42,title:'Recovered'}])
  expect(await query('select * from units')).toHaveLength(1)
})

test('replace preserves shared ownership and advances revisions while keeping runtime guards enabled', async () => {
  await restore({cards:[{id:10,title:'Updated',group_assignment_revision:1}],card_group_assignments:[{card_id:10,group_code:'a',assigned_by:1}]},true)
  expect(await query('select group_code from card_group_assignments order by group_code')).toEqual([{group_code:'a'},{group_code:'b'}])
  expect(Number((await query('select group_assignment_revision n from cards'))[0].n)).toBeGreaterThan(2)
  await rejected('update cards set group_assignment_revision=99','server managed')
})

test('replacement rebuilds derived directory and remaps existing membership', async () => {
  const groups = await query('select * from service_groups order by code')
  await restore({service_groups:groups.map(g => ({...g,display_name:g.code==='a'?'New A':g.display_name}))},true)
  expect(await query('select group_name from app_users')).toEqual([{group_name:'New A'}])
  expect(String((await query("select value from app_settings where key='service_group_directory'"))[0].value)).toContain('New A')
  await rejected("update app_settings set value='[]' where key='user_groups'",'directory management')
})

test('owner-only maintenance cannot be invoked by an ordinary writer', async () => {
  await rejected(`set local role authenticated;${atomicRestoreSql({review_tasks:[{id:8,title:'Denied'}]})}`,'owner')
  expect(await query('select * from review_tasks')).toEqual([])
})

test('missing target, missing key, unknown columns and incomplete business files fail closed', async () => {
  await rejected(atomicRestoreSql({not_a_table:[]}), 'Missing restore table')
  await rejected(atomicRestoreSql({review_tasks:[{title:'No id'}]}),'primary key missing')
  await rejected(atomicRestoreSql({review_tasks:[{id:1,title:'X',unknown:'X'}]}),'Unknown backup column')
  await db.exec('create table event_meeting_access(event_id int primary key)')
  await rejected(atomicRestoreSql({review_tasks:[]},{full:true}),'Incomplete business backup')
})

test('plaintext PINs and inconsistent row shapes are rejected before SQL execution', () => {
  expect(() => atomicRestoreSql({app_users:[{id:1,pin:'1234'}]})).toThrow('hashed PINs')
  expect(() => atomicRestoreSql({units:[{id:1},{id:2,building_id:1}]})).toThrow('columns')
})

test('failure after sequence restart rolls back sequence and rows together', async () => {
  await db.exec("insert into review_tasks(title) values('Existing')")
  const before = await query('select last_value,is_called from review_tasks_id_seq')
  await rejected(atomicRestoreSql({review_tasks:[{id:999,title:'Never committed'}]})+
    "do $$ begin raise exception 'Late failure'; end $$;",'Late failure')
  expect(await query('select last_value,is_called from review_tasks_id_seq')).toEqual(before)
  expect(await query('select title from review_tasks')).toEqual([{title:'Existing'}])
})

test('assignment revisions invalidate stale clients, including missing-only retries', async () => {
  await restore({calendar_events:[{id:100,target_groups:[]}]})
  expect(await query('select revision from private.event_assignment_revisions')).toEqual([{revision:8}])
})

test('a cards-only replacement cannot rewind its current revision', async () => {
  await restore({cards:[{id:10,title:'Recovered',group_assignment_revision:0}]},true)
  expect(await query('select group_assignment_revision from cards')).toEqual([{group_assignment_revision:3}])
})

test('sequence allocation never goes backwards even if high rows were deleted', async () => {
  await db.exec('alter sequence review_tasks_id_seq restart with 1000')
  await restore({review_tasks:[{id:42,title:'Recovered'}]})
  expect(Number((await query("insert into review_tasks(title) values('New') returning id"))[0].id)).toBeGreaterThan(1000)
})
